import type { CashTransaction, ElectricityTransaction, FinanceWallet, Invoice, Lease, Room, Tenant } from "@/types";
import type { Expense, FinanceBudget, RoomInvestment } from "@/types/finance";

export interface FinanceData {
  rooms: Room[];
  leases: Lease[];
  invoices: Invoice[];
  transactions: CashTransaction[];
  wallets: FinanceWallet[];
  expenses: Expense[];
  budgets: FinanceBudget[];
  investments: RoomInvestment[];
  tenants?: Tenant[];
  electricity?: ElectricityTransaction[];
}
export interface DateRange { start: string; end: string }
export interface FinanceEntry {
  id: string; date: string; title: string; category: string; amount: number;
  type: "income" | "expense"; source: "cash" | "expense" | "payment"; room_id?: string | null;
  wallet_id?: string | null; payment_method?: string; notes?: string | null; recorded_by?: string; invoice_id?: string;
}
export function walletCategoryLabel(wallet?: Pick<FinanceWallet, "type" | "category_name"> | null) {
  if (!wallet) return "Belum dialokasikan";
  return wallet.category_name?.trim() || ({ cash: "Kas Tunai", bank: "Bank", ewallet: "E-Wallet", other: "Lainnya" } as const)[wallet.type] || "Rekening";
}

export function localDate(date = new Date()): string {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
}
export function monthRange(month: string): DateRange {
  const [year, m] = month.split("-").map(Number);
  return { start: `${month}-01`, end: `${month}-${new Date(year, m, 0).getDate()}` };
}
export function shiftMonth(month: string, delta: number) {
  const [year, m] = month.split("-").map(Number);
  return localDate(new Date(year, m - 1 + delta, 1)).slice(0, 7);
}
export function monthLabel(month: string) {
  return new Intl.DateTimeFormat("id-ID", { month: "short", year: "numeric" }).format(new Date(`${month}-01T12:00:00`));
}
export const inRange = (date: string, range: DateRange) => date.slice(0, 10) >= range.start && date.slice(0, 10) <= range.end;
const sum = (rows: { amount: number }[]) => rows.reduce((total, row) => total + Number(row.amount || 0), 0);
const normalize = (value: string) => value.toLowerCase().replace(/[^a-z0-9]/g, "");

export function expenseCategory(category: string) {
  const value = normalize(category);
  if (/wifi|internet/.test(value)) return "Internet & WiFi";
  if (/salary|gaji|kebersihan/.test(value)) return "Gaji & Kebersihan";
  if (/utilit|listrik|air/.test(value)) return "Listrik & Air";
  if (/maintenance|perbaikan|perawatan/.test(value)) return "Perawatan";
  if (/security|trash|keamanan|sampah/.test(value)) return "Keamanan & Sampah";
  if (/supplies|perlengkapan/.test(value)) return "Perlengkapan";
  if (/pajak|tax/.test(value)) return "Pajak";
  if (/bunga|interest/.test(value)) return "Bunga";
  return category || "Lainnya";
}

export function transactionInvoice(tx: { title: string; notes?: string | null }, data: Pick<FinanceData, "invoices">) {
  const text = `${tx.title} ${tx.notes || ""}`;
  return data.invoices.find(inv => {
    const escaped = inv.invoice_number.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    return new RegExp(`(^|[^a-z0-9])${escaped}(?![a-z0-9/-])`, "i").test(text);
  });
}
function cashRoom(tx: CashTransaction, data: FinanceData) {
  if (tx.room_id) return tx.room_id;
  const invoice = transactionInvoice(tx, data);
  if (invoice) return invoice.room_id || data.leases.find(l => l.id === invoice.lease_id)?.room_id;
  const number = `${tx.title} ${tx.notes || ""}`.match(/kamar\s+([a-z0-9-]+)/i)?.[1];
  return number ? data.rooms.find(r => r.room_number.toLowerCase() === number.toLowerCase())?.id : undefined;
}

export function invoicePaymentSummary(invoice: Pick<Invoice, "total_amount" | "payments" | "status">) {
  const paid = (invoice.payments || []).reduce((total, payment) => total + Number(payment.amount_paid || 0), 0);
  const total = Math.max(0, Number(invoice.total_amount || 0));
  const settled = (total > 0 && paid >= total) || (invoice.status === "paid" && paid === 0);
  return { paid, outstanding: settled ? 0 : Math.max(0, total - paid), settled };
}

// Use payment records as the canonical source for invoice cash receipts. Legacy
// cash rows generated by verifyPayment are suppressed only when a payment record
// exists, so older installations without payment details remain visible.
export function financeEntries(data: FinanceData): FinanceEntry[] {
  const invoicesWithPayments = new Set(data.invoices.filter(invoice => (invoice.payments || []).length > 0).map(invoice => invoice.id));
  const cashRows = data.transactions.filter(transaction => {
    const invoice = transactionInvoice(transaction, data);
    return !invoice || !invoicesWithPayments.has(invoice.id);
  });
  return [
    ...cashRows.map(tx => ({
      id: tx.id, date: tx.date, title: tx.title,
      category: tx.type === "expense" ? expenseCategory(tx.category_name || tx.category) : tx.category_name || tx.category,
      amount: Number(tx.amount), type: tx.type, source: "cash" as const, room_id: cashRoom(tx, data),
      wallet_id: tx.wallet_id, payment_method: tx.wallet_name || tx.payment_method, notes: tx.notes, recorded_by: tx.recorded_by,
    })),
    ...data.expenses.map(e => ({ ...e, category: expenseCategory(e.category), amount: Number(e.amount), type: "expense" as const, source: "expense" as const })),
    ...data.invoices.flatMap(invoice => (invoice.payments || []).map(payment => ({
      id: payment.id,
      date: (payment.paid_at || payment.created_at || invoice.created_at || invoice.due_date).slice(0, 10),
      title: `Pembayaran ${invoice.invoice_number}`,
      category: "Sewa Kamar",
      amount: Number(payment.amount_paid),
      type: "income" as const,
      source: "payment" as const,
      room_id: invoice.room_id || data.leases.find(lease => lease.id === invoice.lease_id)?.room_id,
      invoice_id: payment.invoice_id,
      wallet_id: payment.wallet_id || null,
      payment_method: payment.wallet_name || payment.payment_method,
      notes: payment.notes || null,
      recorded_by: payment.verified_by,
    }))),
  ];
}

export function walletBalances(data: FinanceData, entries = financeEntries(data), today = localDate()) {
  const rows = entries.filter(e => e.date.slice(0, 10) <= today);
  const assignedWallet = (entry: FinanceEntry) => entry.wallet_id || (() => {
    const matches = data.wallets.filter(w => w.wallet_kind !== "liability" && w.name === entry.payment_method);
    return matches.length === 1 ? matches[0].id : undefined;
  })();
  const wallets = data.wallets.filter(w => w.wallet_kind !== "liability").map(wallet => ({ ...wallet,
    balance: Number(wallet.initial_balance || 0) + rows.filter(e => assignedWallet(e) === wallet.id).reduce((t, e) => t + (e.type === "income" ? e.amount : -e.amount), 0),
  }));
  const ids = new Set(wallets.map(w => w.id));
  const unassigned = rows.filter(e => !ids.has(assignedWallet(e) || "")).reduce((t, e) => t + (e.type === "income" ? e.amount : -e.amount), 0);
  return { wallets, unassigned };
}

export function ownerCashflow(data: FinanceData, timeframe: "30d" | "6m" | "1y", today = localDate()) {
  const entries = financeEntries(data), month = today.slice(0, 7);
  const count = timeframe === "30d" ? 30 : timeframe === "1y" ? 12 : 6;
  return Array.from({ length: count }, (_, i) => {
    const day = new Date(`${today}T12:00:00`); day.setDate(day.getDate() + i - count + 1);
    const key = timeframe === "30d" ? localDate(day) : shiftMonth(month, i - count + 1);
    const range = timeframe === "30d" ? { start: key, end: key } : monthRange(key);
    if (range.end > today) range.end = today;
    const totals = pnl(entries, range);
    const occupied = new Set(data.leases.filter(l => l.status !== "cancelled" && l.start_date <= range.end && (!l.end_date || l.end_date >= range.start)).map(l => l.room_id));
    return { period: timeframe === "30d" ? new Intl.DateTimeFormat("id-ID", { day: "numeric", month: "short" }).format(day) : monthLabel(key),
      Pemasukan: totals.revenue, Pengeluaran: totals.costs, LabaBersih: totals.profit, okupansi: data.rooms.length ? Math.round([...occupied].filter(id => data.rooms.some(r => r.id === id)).length / data.rooms.length * 100) : 0 };
  });
}

export function pnl(entries: FinanceEntry[], range: DateRange) {
  const rows = entries.filter(row => inRange(row.date, range));
  const income = rows.filter(row => row.type === "income");
  const expenses = rows.filter(row => row.type === "expense");
  const rent = income.filter(row => /sewa.*kamar|room.?rent|rent.?room/i.test(row.category));
  const tax = expenses.filter(row => row.category === "Pajak");
  const interest = expenses.filter(row => row.category === "Bunga");
  const operating = expenses.filter(row => row.category !== "Pajak" && row.category !== "Bunga");
  const revenue = sum(income), costs = sum(expenses), profit = revenue - costs;
  const expenseGroups = Object.entries(operating.reduce<Record<string, number>>((groups, row) => {
    groups[row.category] = (groups[row.category] || 0) + row.amount; return groups;
  }, {})).map(([name, value]) => ({ name, value })).sort((a, b) => b.value - a.value);
  return { rows, revenue, costs, profit, rent: sum(rent), otherIncome: revenue - sum(rent), operating: sum(operating), interest: sum(interest), tax: sum(tax), margin: revenue > 0 ? profit / revenue * 100 : null, expenseGroups };
}

export function sixMonthTrend(entries: FinanceEntry[], month: string) {
  return Array.from({ length: 6 }, (_, i) => {
    const key = shiftMonth(month, i - 5), totals = pnl(entries, monthRange(key));
    return { month: key, name: monthLabel(key), revenue: totals.revenue, expenses: totals.costs, profit: totals.profit };
  });
}

export function receivables(invoices: Invoice[], today = localDate()) {
  const rows = invoices.map(invoice => {
    const { outstanding } = invoicePaymentSummary(invoice);
    const days = Math.max(0, Math.floor((Date.parse(`${today}T00:00:00Z`) - Date.parse(`${invoice.due_date.slice(0, 10)}T00:00:00Z`)) / 86400000));
    return { ...invoice, outstanding, days };
  }).filter(row => row.outstanding > 0);
  const aging = [
    { name: "Belum tempo", value: sum(rows.filter(r => r.due_date.slice(0, 10) >= today).map(r => ({ amount: r.outstanding }))) },
    { name: "1–30 hari", value: sum(rows.filter(r => r.days >= 1 && r.days <= 30).map(r => ({ amount: r.outstanding }))) },
    { name: "31–60 hari", value: sum(rows.filter(r => r.days >= 31 && r.days <= 60).map(r => ({ amount: r.outstanding }))) },
    { name: "61–90 hari", value: sum(rows.filter(r => r.days >= 61 && r.days <= 90).map(r => ({ amount: r.outstanding }))) },
    { name: ">90 hari", value: sum(rows.filter(r => r.days > 90).map(r => ({ amount: r.outstanding }))) },
  ];
  return { aging, total: rows.reduce((t, r) => t + r.outstanding, 0), overdue: rows.filter(r => r.days > 0).sort((a, b) => b.days - a.days || b.outstanding - a.outstanding) };
}

export function unitEconomics(data: FinanceData, entries: FinanceEntry[], range: DateRange) {
  const rows = entries.filter(e => inRange(e.date, range));
  const ids = new Set(data.rooms.map(r => r.id));
  const shared = rows.filter(e => !e.room_id || !ids.has(e.room_id));
  const divisor = data.rooms.length || 1;
  const sharedRevenue = sum(shared.filter(e => e.type === "income")) / divisor;
  const sharedCosts = sum(shared.filter(e => e.type === "expense")) / divisor;
  return data.rooms.map(room => {
    const direct = rows.filter(e => e.room_id === room.id);
    const revenue = sum(direct.filter(e => e.type === "income")) + sharedRevenue;
    const costs = sum(direct.filter(e => e.type === "expense")) + sharedCosts;
    const investment = Number(data.investments.find(i => i.room_id === room.id)?.amount || 0);
    return { room, revenue, costs, sharedRevenue, sharedCosts, profit: revenue - costs, investment, roi: investment > 0 ? (revenue - costs) / investment * 100 : null };
  }).sort((a, b) => b.profit - a.profit || a.room.room_number.localeCompare(b.room.room_number));
}

export function financeKpis(data: FinanceData, entries: FinanceEntry[], month: string) {
  const range = monthRange(month), totals = pnl(entries, range);
  const occupied = new Set(data.leases.filter(l => l.start_date <= range.end && (!l.end_date || l.end_date >= range.start) && l.status !== "cancelled").map(l => l.room_id)).size;
  const averageRent = data.rooms.length ? data.rooms.reduce((t, r) => t + Number(r.base_price), 0) / data.rooms.length : 0;
  const cashRows = entries.filter(e => e.date.slice(0, 10) <= localDate());
  const cash = data.wallets.filter(w => w.wallet_kind !== "liability").reduce((t, w) => t + Number(w.initial_balance || 0), 0) + sum(cashRows.filter(e => e.type === "income")) - sum(cashRows.filter(e => e.type === "expense"));
  return { ...totals, cash, occupied, arpu: occupied > 0 ? totals.revenue / occupied : null, bep: averageRent > 0 ? Math.ceil(totals.costs / averageRent) : null };
}

export function budgetComparison(data: FinanceData, entries: FinanceEntry[], month: string) {
  const budgets = data.budgets.filter(b => b.month === month);
  const actuals = entries.filter(e => e.type === "expense" && inRange(e.date, monthRange(month)));
  const categories = [...new Set([...budgets.map(b => expenseCategory(b.category)), ...actuals.map(e => e.category)])];
  return categories.map(category => {
    const budgetRows = budgets.filter(b => expenseCategory(b.category) === category);
    const budget = sum(budgetRows), actual = sum(actuals.filter(e => e.category === category));
    return { name: category, budget, actual, hasBudget: budgetRows.length > 0, variance: budget - actual };
  }).sort((a, b) => b.actual - a.actual);
}

export function projection(entries: FinanceEntry[], month: string, growth: number) {
  const historical = [-3, -2, -1].map(delta => pnl(entries, monthRange(shiftMonth(month, delta))));
  const revenue = historical.reduce((t, p) => t + p.revenue, 0) / 3;
  const expenses = historical.reduce((t, p) => t + p.costs, 0) / 3;
  return { hasHistory: historical.some(p => p.rows.length > 0), rows: [1, 2, 3].map(offset => {
    const key = shiftMonth(month, offset), projectedRevenue = revenue * Math.pow(1 + growth / 100, offset);
    return { name: monthLabel(key), revenue: projectedRevenue, expenses, profit: projectedRevenue - expenses };
  }) };
}
